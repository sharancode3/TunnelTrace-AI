"""
TunnelTrace AI - Defensive Lab PCAP Mutator & Parser Resilience Harness
========================================================================
Implements typed, bounded packet mutations against lab-generated PCAPs to evaluate
dissector boundaries, unmapped SA handling, out-of-order delivery, and parser resilience.

PROVENANCE & LICENSE NOTICE:
- Scapy is an optional dependency licensed under GNU GPL v2.
- Scapy is strictly confined to isolated lab testing and offline PCAP mutation.
- It is never loaded into the production web API or asynchronous worker runtime.
- A pure-Python fallback PCAP parser/mutator is provided so that offline mutation
  operates deterministically regardless of whether Scapy is installed.
- Zero raw socket operations are permitted against host physical interfaces or external networks.
"""

import hashlib
import logging
import os
import struct
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from pydantic import BaseModel, Field, field_validator

from lab.agent.operations.runner import PROTECTED_HOST_INTERFACES, SecurityViolationError

logger = logging.getLogger(__name__)

# Detect optional Scapy availability
try:
    import scapy
    from scapy.all import Packet, Raw, rdpcap, wrpcap  # type: ignore

    SCAPY_AVAILABLE = True
    SCAPY_VERSION = getattr(scapy, "__version__", "unknown")
except (ImportError, Exception):
    SCAPY_AVAILABLE = False
    SCAPY_VERSION = None


class MutationType(str, Enum):
    """Supported deterministic typed mutation operators."""

    TRUNCATE_HEADER = "TRUNCATE_HEADER"  # Truncates packet below minimum header size to test parser boundary checks
    CORRUPT_SPI = "CORRUPT_SPI"  # Corrupts SPI value to test unmapped/orphan SA handling
    REORDER_PACKETS = "REORDER_PACKETS"  # Swaps adjacent packet records to test out-of-order arrival
    CORRUPT_CHECKSUM = "CORRUPT_CHECKSUM"  # Invalidates UDP checksum bytes to test transport validation
    CORRUPT_PAYLOAD_LENGTH = "CORRUPT_PAYLOAD_LENGTH"  # Injects discrepancy between advertised length and packet bytes


class MutationConfig(BaseModel):
    """Typed, constrained specification for a lab PCAP mutation experiment."""

    mutation_id: str = Field(..., description="Unique alphanumeric identifier (e.g. 'mut-ike-trunc-01')")
    mutation_type: MutationType = Field(..., description="Deterministic typed mutation operator")
    target_layer: str = Field("IKE", description="Target layer ('IKE', 'ESP', 'UDP')")
    byte_offset: Optional[int] = Field(None, ge=0, le=1500, description="Optional explicit byte offset to mutate")
    max_packets: int = Field(5, ge=1, le=20, description="Strict maximum number of packets to mutate")
    seed: int = Field(42, description="Deterministic PRNG seed for repeatability")

    @field_validator("mutation_id")
    @classmethod
    def validate_mutation_id(cls, v: str) -> str:
        if not v or not v.replace("-", "").replace("_", "").isalnum():
            raise ValueError(f"Invalid mutation_id '{v}': Must be alphanumeric with hyphens/underscores.")
        return v


class MutationResult(BaseModel):
    """Auditable evidence record generated by a PCAP mutation experiment."""

    mutation_id: str
    mutation_type: MutationType
    tool_used: str  # "SCAPY" or "PURE_PYTHON_FALLBACK"
    tool_version: Optional[str]
    source_pcap_path: str
    source_pcap_sha256: str
    mutated_pcap_path: str
    mutated_pcap_sha256: str
    packets_processed: int
    packets_mutated: int
    parser_robustness_tested: bool = False
    parser_observations_count: int = 0
    parser_errors_flagged: List[str] = Field(default_factory=list)
    live_transmission_status: str = "OFFLINE_ONLY"


def _sha256_file(path: str) -> str:
    """Compute SHA-256 digest of a file."""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


class PcapMutator:
    """
    Offline PCAP mutator supporting both Scapy and pure-Python binary byte-level mutation.
    Guarantees deterministic execution without requiring root or external dependencies.
    """

    @classmethod
    def mutate_pcap(
        cls,
        source_pcap: str,
        output_pcap: str,
        config: MutationConfig,
    ) -> MutationResult:
        """
        Applies typed mutation to a source PCAP and writes the mutated PCAP to output_pcap.
        Never modifies the source PCAP file in place.
        """
        if not os.path.isfile(source_pcap):
            raise FileNotFoundError(f"Source PCAP file not found: {source_pcap}")

        os.makedirs(os.path.dirname(os.path.abspath(output_pcap)), exist_ok=True)
        src_hash = _sha256_file(source_pcap)

        if SCAPY_AVAILABLE:
            tool_used = "SCAPY"
            tool_ver = SCAPY_VERSION
            processed, mutated = cls._mutate_with_scapy(source_pcap, output_pcap, config)
        else:
            tool_used = "PURE_PYTHON_FALLBACK"
            tool_ver = "3.10-builtin"
            processed, mutated = cls._mutate_pure_python(source_pcap, output_pcap, config)

        mutated_hash = _sha256_file(output_pcap)

        return MutationResult(
            mutation_id=config.mutation_id,
            mutation_type=config.mutation_type,
            tool_used=tool_used,
            tool_version=tool_ver,
            source_pcap_path=source_pcap,
            source_pcap_sha256=src_hash,
            mutated_pcap_path=output_pcap,
            mutated_pcap_sha256=mutated_hash,
            packets_processed=processed,
            packets_mutated=mutated,
            parser_robustness_tested=False,
            live_transmission_status="OFFLINE_ONLY",
        )

    @classmethod
    def _mutate_pure_python(
        cls,
        source_pcap: str,
        output_pcap: str,
        config: MutationConfig,
    ) -> Tuple[int, int]:
        """
        Pure Python implementation of standard Libpcap format mutation.
        Reads 24-byte global header and 16-byte packet record headers.
        """
        with open(source_pcap, "rb") as f_in:
            data = f_in.read()

        if len(data) < 24:
            raise ValueError(f"File '{source_pcap}' is too small to be a valid PCAP (size: {len(data)} bytes).")

        magic = struct.unpack("<I", data[:4])[0]

        if magic == 0x0A0D0D0A:
            # PCAPNG Format (Section Header Block, Interface Description Block, Enhanced Packet Blocks)
            offset = 0
            blocks: List[Tuple[int, bytes]] = []
            epb_indices: List[int] = []

            while offset + 8 <= len(data):
                b_type, b_len = struct.unpack("<II", data[offset : offset + 8])
                if b_len < 12 or offset + b_len > len(data):
                    break
                b_data = data[offset : offset + b_len]
                if b_type == 0x00000006:  # Enhanced Packet Block
                    epb_indices.append(len(blocks))
                blocks.append((b_type, b_data))
                offset += b_len

            total_packets = len(epb_indices)
            mutated_count = 0

            if config.mutation_type == MutationType.REORDER_PACKETS and len(epb_indices) >= 2:
                idx1, idx2 = epb_indices[0], epb_indices[1]
                blocks[idx1], blocks[idx2] = blocks[idx2], blocks[idx1]
                mutated_count = 2
            else:
                for count, blk_idx in enumerate(epb_indices):
                    if count < config.max_packets:
                        b_type, b_bytes = blocks[blk_idx]
                        b_arr = bytearray(b_bytes)
                        # EPB layout: 0..3: type, 4..7: len, 8..11: if_id, 12..19: ts, 20..23: cap_len, 24..27: orig_len, 28..: pkt
                        cap_len = struct.unpack("<I", b_arr[20:24])[0]
                        pkt_data_start = 28
                        pkt_bytes = b_arr[pkt_data_start : pkt_data_start + cap_len]

                        if config.mutation_type == MutationType.TRUNCATE_HEADER:
                            new_cap_len = min(14, len(pkt_bytes))
                            struct.pack_into("<I", b_arr, 20, new_cap_len)
                            padded_len = (new_cap_len + 3) & ~3
                            new_total_len = 32 + padded_len
                            struct.pack_into("<I", b_arr, 4, new_total_len)
                            new_block = bytearray(new_total_len)
                            new_block[:28] = b_arr[:28]
                            new_block[28 : 28 + new_cap_len] = pkt_bytes[:new_cap_len]
                            struct.pack_into("<I", new_block, new_total_len - 4, new_total_len)
                            blocks[blk_idx] = (b_type, bytes(new_block))
                            mutated_count += 1

                        elif config.mutation_type == MutationType.CORRUPT_SPI:
                            target_offset = config.byte_offset if config.byte_offset is not None else 28
                            abs_offset = pkt_data_start + target_offset
                            if abs_offset + 8 <= len(b_arr) - 4:
                                b_arr[abs_offset : abs_offset + 8] = b"\x00\x00\x00\x00\x00\x00\x00\x00"
                                blocks[blk_idx] = (b_type, bytes(b_arr))
                                mutated_count += 1

                        elif config.mutation_type == MutationType.CORRUPT_CHECKSUM:
                            target_offset = config.byte_offset if config.byte_offset is not None else 26
                            abs_offset = pkt_data_start + target_offset
                            if abs_offset + 2 <= len(b_arr) - 4:
                                b_arr[abs_offset : abs_offset + 2] = b"\xff\xff"
                                blocks[blk_idx] = (b_type, bytes(b_arr))
                                mutated_count += 1

                        elif config.mutation_type == MutationType.CORRUPT_PAYLOAD_LENGTH:
                            orig_len = struct.unpack("<I", b_arr[24:28])[0]
                            struct.pack_into("<I", b_arr, 24, orig_len + 200)
                            blocks[blk_idx] = (b_type, bytes(b_arr))
                            mutated_count += 1

            with open(output_pcap, "wb") as f_out:
                for _, b_bytes in blocks:
                    f_out.write(b_bytes)

            return total_packets, mutated_count

        if magic in (0xA1B2C3D4, 0xA1B23C4D):
            endian = "<"
        elif magic in (0xD4C3B2A1, 0x4D3CB2A1):
            endian = ">"
        else:
            raise ValueError(f"Unrecognized PCAP magic number: {hex(magic)}")

        global_header = data[:24]
        offset = 24
        packet_records: List[Tuple[bytes, bytes]] = []  # (hdr_16, payload_bytes)

        while offset + 16 <= len(data):
            hdr = data[offset : offset + 16]
            ts_sec, ts_usec, incl_len, orig_len = struct.unpack(f"{endian}IIII", hdr)
            pkt_data = data[offset + 16 : offset + 16 + incl_len]
            packet_records.append((hdr, pkt_data))
            offset += 16 + incl_len

        total_packets = len(packet_records)
        mutated_count = 0
        new_records: List[Tuple[bytes, bytes]] = []

        if config.mutation_type == MutationType.REORDER_PACKETS and len(packet_records) >= 2:
            packet_records[0], packet_records[1] = packet_records[1], packet_records[0]
            new_records = packet_records
            mutated_count = 2
        else:
            for idx, (hdr, pkt_data) in enumerate(packet_records):
                if idx < config.max_packets:
                    pkt_bytes = bytearray(pkt_data)
                    ts_sec, ts_usec, incl_len, orig_len = struct.unpack(f"{endian}IIII", hdr)

                    if config.mutation_type == MutationType.TRUNCATE_HEADER:
                        new_len = min(14, len(pkt_bytes))
                        pkt_bytes = pkt_bytes[:new_len]
                        hdr = struct.pack(f"{endian}IIII", ts_sec, ts_usec, len(pkt_bytes), orig_len)
                        mutated_count += 1

                    elif config.mutation_type == MutationType.CORRUPT_SPI:
                        target_offset = config.byte_offset if config.byte_offset is not None else min(28, len(pkt_bytes) - 8)
                        if target_offset + 8 <= len(pkt_bytes):
                            pkt_bytes[target_offset : target_offset + 8] = b"\x00\x00\x00\x00\x00\x00\x00\x00"
                            mutated_count += 1

                    elif config.mutation_type == MutationType.CORRUPT_CHECKSUM:
                        target_offset = config.byte_offset if config.byte_offset is not None else min(26, len(pkt_bytes) - 2)
                        if target_offset + 2 <= len(pkt_bytes):
                            pkt_bytes[target_offset : target_offset + 2] = b"\xff\xff"
                            mutated_count += 1

                    elif config.mutation_type == MutationType.CORRUPT_PAYLOAD_LENGTH:
                        fake_len = incl_len + 100
                        hdr = struct.pack(f"{endian}IIII", ts_sec, ts_usec, incl_len, fake_len)
                        mutated_count += 1

                    new_records.append((hdr, bytes(pkt_bytes)))
                else:
                    new_records.append((hdr, pkt_data))

        with open(output_pcap, "wb") as f_out:
            f_out.write(global_header)
            for hdr, pkt in new_records:
                f_out.write(hdr)
                f_out.write(pkt)

        return total_packets, mutated_count

    @classmethod
    def _mutate_with_scapy(
        cls,
        source_pcap: str,
        output_pcap: str,
        config: MutationConfig,
    ) -> Tuple[int, int]:
        """Scapy-based mutation when Scapy is available."""
        packets = list(rdpcap(source_pcap))
        total_packets = len(packets)
        mutated_count = 0

        if config.mutation_type == MutationType.REORDER_PACKETS and len(packets) >= 2:
            packets[0], packets[1] = packets[1], packets[0]
            mutated_count = 2
        else:
            for idx in range(min(len(packets), config.max_packets)):
                pkt = packets[idx]
                raw_bytes = bytearray(bytes(pkt))

                if config.mutation_type == MutationType.TRUNCATE_HEADER:
                    raw_bytes = raw_bytes[: min(14, len(raw_bytes))]
                    packets[idx] = Raw(bytes(raw_bytes))
                    mutated_count += 1

                elif config.mutation_type == MutationType.CORRUPT_SPI:
                    target_offset = config.byte_offset if config.byte_offset is not None else min(28, len(raw_bytes) - 8)
                    if target_offset + 8 <= len(raw_bytes):
                        raw_bytes[target_offset : target_offset + 8] = b"\x00\x00\x00\x00\x00\x00\x00\x00"
                        packets[idx] = Raw(bytes(raw_bytes))
                        mutated_count += 1

                elif config.mutation_type == MutationType.CORRUPT_CHECKSUM:
                    target_offset = config.byte_offset if config.byte_offset is not None else min(26, len(raw_bytes) - 2)
                    if target_offset + 2 <= len(raw_bytes):
                        raw_bytes[target_offset : target_offset + 2] = b"\xff\xff"
                        packets[idx] = Raw(bytes(raw_bytes))
                        mutated_count += 1

                elif config.mutation_type == MutationType.CORRUPT_PAYLOAD_LENGTH:
                    # Invalidate length by appending truncated raw bytes
                    raw_bytes = raw_bytes[: len(raw_bytes) - 4]
                    packets[idx] = Raw(bytes(raw_bytes))
                    mutated_count += 1

        wrpcap(output_pcap, packets)
        return total_packets, mutated_count

    @classmethod
    def transmit_mutated_live_guard(
        cls,
        namespace: str,
        interface: str,
        packet_count: int,
    ) -> Dict[str, Any]:
        """
        Strict security boundary guard for any live packet mutation injection.
        Guarantees that packets are NEVER transmitted to physical host interfaces
        or outside a verified 'tt-*' lab namespace.
        """
        # 1. Assert namespace belongs to TunnelTrace lab
        if not namespace or not namespace.startswith("tt-"):
            raise SecurityViolationError(
                f"Live mutation transmission refused: namespace '{namespace}' does not start with 'tt-'"
            )

        # 2. Assert interface is not a protected physical interface
        if (
            interface in PROTECTED_HOST_INTERFACES
            or interface.startswith(("eth0", "enp", "wlan", "docker", "tailscale"))
            or "Ethernet" in interface
            or "Wi-Fi" in interface
        ):
            raise SecurityViolationError(
                f"Live mutation transmission refused: interface '{interface}' is a protected physical interface."
            )

        # 3. Rate and count boundary
        if packet_count > 10:
            raise SecurityViolationError(
                f"Live mutation transmission refused: packet count ({packet_count}) exceeds safety limit of 10."
            )

        # 4. Check Linux root / raw socket capability
        # If on Windows host or unprivileged environment, refuse live transmission truthfully
        is_windows = os.name == "nt"
        if is_windows:
            return {
                "allowed": False,
                "status": "BLOCKED",
                "reason": "Live Scapy packet injection requires root raw sockets inside a Linux network namespace. Blocked on Windows host.",
            }

        return {
            "allowed": True,
            "status": "AUTHORIZED_LAB_ONLY",
            "namespace": namespace,
            "interface": interface,
            "packet_count": packet_count,
        }
